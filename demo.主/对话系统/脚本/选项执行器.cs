using Godot;
using System.Collections.Generic;
using 你的项目.Scripts.角色;
using 你的项目.Scripts.资源;
using 你的项目.Scripts.管理器;

public class 选项执行器
{
	public enum 执行结果
	{
		继续对话,
		结束对话,
		切换场景,
		显示场景UI,
		开始教程战斗
	}

	public 对话状态存储 对话状态存储实例 { get; set; }

	// ===================== 主入口 =====================

	public (执行结果 结果, string 场景路径, 对话序列 后续对话) 执行(分支选项 选项, 对话序列 当前序列, int 选项索引)
	{
		GD.Print($"[选项执行器] 执行选项: 序列={当前序列?.ResourcePath}, 选项文本={选项.选项文本}");

		// 1. 处理奖励道具（战斗胜利后获得）
		_处理奖励道具(选项);

		// 2. 处理立即获得道具
		_处理立即获得道具(选项);

		// 3. 处理标记对话序列改变
		_处理标记改变(选项);

		// ===== ★ 处理接取任务 =====
		if (选项.接取任务资源 != null)
		{
			string 源路径 = 选项.任务完成后要改变的源序列路径;
			if (string.IsNullOrEmpty(源路径))
				源路径 = 当前序列?.ResourcePath;

			string 目标路径 = 选项.任务完成后目标改变序列?.ResourcePath;

			任务管理器.实例?.接取任务(选项.接取任务资源, 源路径, 目标路径);
		}

		// 4. 处理战斗（教程 + 普通）
		var 战斗结果 = _处理战斗(选项, 当前序列, 选项索引);
		if (战斗结果 != null) return 战斗结果.Value;

		// 5. 处理奖励卡组
		_处理奖励卡组(选项);

		// 6. 处理触发条件
		_处理触发条件(选项);

		// 7. 处理对话结束后场景切换
		var 场景切换结果 = _处理对话后场景切换(选项, 当前序列, 选项索引);
		if (场景切换结果 != null) return 场景切换结果.Value;

		// 8. 处理显示场景UI
		var 场景UI结果 = _处理显示场景UI(选项);
		if (场景UI结果 != null) return 场景UI结果.Value;

		// 9. 处理传送
		var 传送结果 = _处理传送(选项, 当前序列, 选项索引);
		if (传送结果 != null) return 传送结果.Value;

		// 10. 继续对话或结束
		return _处理继续或结束(选项);
	}

	// ===================== 子方法 =====================

	private void _处理奖励道具(分支选项 选项)
	{
		if (选项.胜利后获得道具列表 != null && 选项.胜利后获得道具列表.Count > 0)
		{
			卡牌数据管理器.上下文.待奖励道具列表 = 选项.胜利后获得道具列表;
			GD.Print($"[选项执行器] 暂存了 {选项.胜利后获得道具列表.Count} 个道具作为战斗胜利奖励");
		}
		else
		{
			卡牌数据管理器.上下文.待奖励道具列表 = null;
		}
	}

	private void _处理立即获得道具(分支选项 选项)
	{
		if (选项.选择后获得道具列表 == null || 选项.选择后获得道具列表.Count == 0) return;

		foreach (var 道具 in 选项.选择后获得道具列表)
		{
			if (道具 == null) continue;
			var 克隆 = 道具.克隆();
			玩家道具管理器.实例?.添加道具(克隆);
			GD.Print($"[选项执行器] 立即获得道具: {克隆.名称} x{克隆.数量}");
		}
	}

	private void _处理标记改变(分支选项 选项)
	{
		if (string.IsNullOrEmpty(选项.选项触发后改变对话序列路径)) return;

		var 当前状态 = 存档管理器.实例?.获取当前状态();
		if (当前状态 == null) return;

		当前状态.设置对话改变状态(选项.选项触发后改变对话序列路径, true);
		GD.Print($"[选项执行器] 标记对话序列为已改变: {选项.选项触发后改变对话序列路径}");

		if (选项.选项触发后目标改变序列 != null)
		{
			string 目标路径 = 选项.选项触发后目标改变序列.ResourcePath;
			当前状态.设置对话改变目标序列(选项.选项触发后改变对话序列路径, 目标路径);
			GD.Print($"[选项执行器] 设置改变后目标序列: {选项.选项触发后改变对话序列路径} → {目标路径}");
		}
	}

	// ===== 战斗处理 =====

	private (执行结果 结果, string 场景路径, 对话序列 后续对话)? _处理战斗(分支选项 选项, 对话序列 当前序列, int 选项索引)
	{
		if (!选项.对话后触发战斗) return null;

		// 教程战斗
		if (选项.教程战斗配置 != null)
			return _处理教程战斗(选项, 当前序列, 选项索引);

		// 普通战斗
		return _处理普通战斗(选项, 当前序列, 选项索引);
	}

	private (执行结果 结果, string 场景路径, 对话序列 后续对话) _处理教程战斗(分支选项 选项, 对话序列 当前序列, int 选项索引)
	{
		卡牌数据管理器.上下文.待启动的教程战斗配置 = 选项.教程战斗配置;
		准备战斗切换(选项, 当前序列, 选项索引);

		_设置战斗后改变对话(选项, 当前序列);
		卡牌数据管理器.上下文.战斗后返回对话序列 = 选项.战斗胜利后返回对话序列;

		if (选项.目标序列 != null)
		{
			卡牌数据管理器.上下文.待触发战斗场景路径 = "res://卡牌系统/场景/卡牌战斗场景.tscn";
			卡牌数据管理器.上下文.待触发战斗转场动画 = 选项.转场动画配置;
			return (执行结果.继续对话, "", 选项.目标序列);
		}

		return (执行结果.切换场景, "res://卡牌系统/场景/卡牌战斗场景.tscn", null);
	}

	private (执行结果 结果, string 场景路径, 对话序列 后续对话) _处理普通战斗(分支选项 选项, 对话序列 当前序列, int 选项索引)
	{
		准备战斗切换(选项, 当前序列, 选项索引);
		_设置战斗后改变对话(选项, 当前序列);
		卡牌数据管理器.上下文.战斗后返回对话序列 = 选项.战斗胜利后返回对话序列;

		if (选项.目标序列 != null)
		{
			卡牌数据管理器.上下文.待触发战斗场景路径 = "res://卡牌系统/场景/卡牌战斗场景.tscn";
			卡牌数据管理器.上下文.待触发战斗转场动画 = 选项.转场动画配置;
			return (执行结果.继续对话, "", 选项.目标序列);
		}

		return (执行结果.切换场景, "res://卡牌系统/场景/卡牌战斗场景.tscn", null);
	}

	private void 准备战斗切换(分支选项 选项, 对话序列 当前序列, int 选项索引)
	{
		跟随者管理器.实例?.隐藏所有跟随者();

		if (对话播放器.实例 != null)
		{
			卡牌数据管理器.上下文.返回场景路径 = 对话播放器.实例.GetTree().CurrentScene.SceneFilePath;
			if (卡牌数据管理器.上下文.使用动画结束位置)
			{
				卡牌数据管理器.上下文.返回玩家位置 = 卡牌数据管理器.上下文.动画结束位置;
				卡牌数据管理器.上下文.使用动画结束位置 = false;
			}
			else
			{
				var 玩家节点 = 获取玩家节点();
				if (玩家节点 != null)
					卡牌数据管理器.上下文.返回玩家位置 = 玩家节点.GlobalPosition;
			}
		}

		// ★ 战斗胜利后自动隐藏对话触发器（使用名称）
		if (选项.战斗胜利后消失 && !string.IsNullOrEmpty(选项.要隐藏的触发器名称))
		{
			卡牌数据管理器.上下文.战斗胜利后隐藏触发器名称 = 选项.要隐藏的触发器名称;
			GD.Print($"[选项执行器] 战斗胜利后将隐藏触发器: {选项.要隐藏的触发器名称}");
		}
		else
		{
			卡牌数据管理器.上下文.战斗胜利后隐藏触发器名称 = null;
		}

		卡牌数据管理器.上下文.从战斗返回 = true;
		卡牌数据管理器.上下文.战斗胜利金币奖励 = 选项.战斗胜利金币奖励;
		卡牌数据管理器.上下文.临时怪物队伍 = 选项.怪物队伍;
	}

	private void _设置战斗后改变对话(分支选项 选项, 对话序列 当前序列)
	{
		if (选项.战斗胜利后改变对话序列 != null)
			卡牌数据管理器.上下文.待改变对话序列 = 选项.战斗胜利后改变对话序列;

		if (选项.战斗胜利后改变当前对话)
		{
			卡牌数据管理器.上下文.待改变对话序列 = 当前序列;
			if (当前序列.改变后序列 != null)
				卡牌数据管理器.上下文.返回后自动触发对话序列 = 当前序列.改变后序列;
		}
	}

	// ===== 其他处理 =====

	private void _处理奖励卡组(分支选项 选项)
	{
		if (选项.奖励卡组 != null && 选项.奖励卡组.卡组.Count > 0)
			玩家卡组管理器.实例?.添加卡牌列表(选项.奖励卡组.卡组);
	}

	private void _处理触发条件(分支选项 选项)
	{
		if (string.IsNullOrEmpty(选项.触发条件名称)) return;

		条件管理器.实例?.设置条件满足(选项.触发条件名称);
		var 当前场景 = 对话播放器.实例?.GetTree().CurrentScene;
		if (当前场景 != null)
		{
			var 根节点 = 当前场景.GetNodeOrNull<场景根节点_梦世界入口>("场景根节点_梦世界入口");
			根节点?.刷新所有触发器();
		}
	}

	private (执行结果 结果, string 场景路径, 对话序列 后续对话)? _处理对话后场景切换(分支选项 选项, 对话序列 当前序列, int 选项索引)
	{
		if (!选项.对话后触发场景切换 || string.IsNullOrEmpty(选项.对话后目标场景路径))
			return null;

		准备战斗切换(选项, 当前序列, 选项索引);
		_设置战斗后改变对话(选项, 当前序列);
		return (执行结果.切换场景, 选项.对话后目标场景路径, null);
	}

	private (执行结果 结果, string 场景路径, 对话序列 后续对话)? _处理显示场景UI(分支选项 选项)
	{
		if (!选项.显示场景 || string.IsNullOrEmpty(选项.场景路径))
			return null;

		if (选项.目标序列 != null)
		{
			if (对话播放器.实例 != null)
				对话播放器.实例.设置待显示场景(选项.场景路径, 选项.场景后对话序列);
			return (执行结果.继续对话, "", 选项.目标序列);
		}

		return (执行结果.显示场景UI, 选项.场景路径, 选项.场景后对话序列 ?? 选项.目标序列);
	}

	private (执行结果 结果, string 场景路径, 对话序列 后续对话)? _处理传送(分支选项 选项, 对话序列 当前序列, int 选项索引)
	{
		if (!选项.触发场景切换 || string.IsNullOrEmpty(选项.目标场景路径))
			return null;

		准备普通传送(选项, 当前序列, 选项索引);
		_设置战斗后改变对话(选项, 当前序列);
		return (执行结果.切换场景, 选项.目标场景路径, null);
	}

	private (执行结果 结果, string 场景路径, 对话序列 后续对话) _处理继续或结束(分支选项 选项)
	{
		if (选项.目标序列 != null)
			return (执行结果.继续对话, "", 选项.目标序列);
		return (执行结果.结束对话, "", null);
	}

	// ===================== 辅助方法 =====================

	private void 准备普通传送(分支选项 选项, 对话序列 当前序列, int 选项索引)
	{
		if (选项.返回原地)
		{
			if (对话播放器.实例 != null)
			{
				卡牌数据管理器.上下文.返回场景路径 = 对话播放器.实例.GetTree().CurrentScene.SceneFilePath;
				if (卡牌数据管理器.上下文.使用动画结束位置)
				{
					卡牌数据管理器.上下文.返回玩家位置 = 卡牌数据管理器.上下文.动画结束位置;
					卡牌数据管理器.上下文.使用动画结束位置 = false;
				}
				else
				{
					var 玩家节点 = 获取玩家节点();
					if (玩家节点 != null)
						卡牌数据管理器.上下文.返回玩家位置 = 玩家节点.GlobalPosition;
				}
			}
			卡牌数据管理器.上下文.从战斗返回 = true;
			卡牌数据管理器.上下文.临时怪物队伍 = 选项.怪物队伍;
		}
		else
		{
			卡牌数据管理器.上下文.从战斗返回 = false;
			卡牌数据管理器.上下文.返回场景路径 = "";
			卡牌数据管理器.上下文.返回玩家位置 = Vector2.Zero;
			卡牌数据管理器.上下文.临时怪物队伍 = null;
		}

		if (选项.传送后触发对话 && 选项.传送后对话序列 != null)
		{
			string 标识 = $"{当前序列.ResourcePath}|{选项索引}";
			bool 已触发 = 对话状态存储实例?.是否已触发传送后对话(标识) ?? false;
			if (!(选项.是否只能触发一次 && 已触发))
			{
				GD.Print($"[选项执行器] 设置传送后对话: 序列={选项.传送后对话序列?.ResourcePath}, 触发一次={选项.是否只能触发一次}");
				对话播放器.实例?.设置待触发传送后对话(选项.传送后对话序列);
				if (选项.是否只能触发一次)
					对话状态存储实例?.设置传送后对话已触发(标识, true);
			}
		}
	}

	private Node2D 获取玩家节点()
	{
		if (对话播放器.实例 == null) return null;
		var 玩家组 = 对话播放器.实例.GetTree().GetNodesInGroup("玩家");
		if (玩家组.Count > 0) return 玩家组[0] as Node2D;
		return null;
	}

	private 卡牌战斗单位 生成玩家单位(分支选项 选项)
	{
		var 玩家 = new 卡牌战斗单位();
		玩家.名字 = "玩家";
		玩家.生命值 = 50;
		玩家.速度值 = 80;
		Godot.Collections.Array<卡牌数据> 玩家卡组数据 = 获取玩家卡组数据();
		if (选项.奖励卡组 != null && 选项.奖励卡组.卡组.Count > 0)
		{
			foreach (var 卡牌数据 in 选项.奖励卡组.卡组)
				玩家卡组数据.Add(卡牌数据);
		}
		玩家.初始化卡组(玩家卡组数据);
		return 玩家;
	}

	private List<卡牌战斗单位> 生成怪物队伍(怪物队伍配置 配置)
	{
		var 怪物列表 = new List<卡牌战斗单位>();
		if (配置 == null || 配置.怪物列表.Count == 0)
			return 怪物列表;

		foreach (var 怪物配置 in 配置.怪物列表)
		{
			var 怪物 = new 卡牌战斗单位();
			怪物.名字 = 怪物配置.名字;
			怪物.生命值 = 怪物配置.最大生命值;
			怪物.护盾值 = 怪物配置.初始护盾;
			怪物.速度值 = 怪物配置.速度值;
			if (怪物配置.卡组 != null && 怪物配置.卡组.卡组.Count > 0)
				怪物.初始化卡组(怪物配置.卡组.卡组);
			else
				怪物.初始化卡组(new Godot.Collections.Array<卡牌数据>());
			怪物列表.Add(怪物);
		}
		return 怪物列表;
	}

	private Godot.Collections.Array<卡牌数据> 获取玩家卡组数据()
	{
		return new Godot.Collections.Array<卡牌数据>();
	}
}
