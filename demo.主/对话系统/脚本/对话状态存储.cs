using Godot;
using System.Collections.Generic;
using 你的项目.Scripts.管理器;
using 你的项目.Scripts.资源;

// 对话状态存储 - 对接存档管理器，实现持久化
public class 对话状态存储
{
	private int _当前存档位 = 0;
	
	// 设置当前存档位（在游戏开始时由外部设置，比如转场管理器传入）
	public void 设置存档位(int 存档位)
	{
		_当前存档位 = 存档位;
	}
	
	// 获取存档数据（辅助方法）
	private 存档数据资源 获取存档()
	{
		return 存档管理器.实例?.获取存档数据(_当前存档位);
	}
	
	// ---------- 可改变对话状态 ----------
	public bool 是否已改变过(string 序列路径)
	{
		var 存档 = 获取存档();
		return 存档?.获取对话改变状态(序列路径) ?? false;
	}
	
	public void 设置已改变(string 序列路径, bool 已改变)
	{
		var 存档 = 获取存档();
		存档?.设置对话改变状态(序列路径, 已改变);
		GD.Print($"对话状态存储: 设置对话改变状态 {序列路径} = {已改变}");
	}
	
	// ---------- ★ 对话改变目标序列（分支选项指定） ----------
	public string 获取对话改变目标序列(string 序列路径)
	{
		var 存档 = 获取存档();
		return 存档?.获取对话改变目标序列(序列路径) ?? "";
	}
	
	public void 设置对话改变目标序列(string 序列路径, string 目标路径)
	{
		var 存档 = 获取存档();
		if (存档 != null)
		{
			存档.设置对话改变目标序列(序列路径, 目标路径);
			GD.Print($"对话状态存储: 设置对话改变目标序列 {序列路径} → {目标路径}");
		}
	}
	
	// ---------- 传送后对话触发记录 ----------
	public bool 是否已触发传送后对话(string 唯一标识)
	{
		var 存档 = 获取存档();
		return 存档?.获取传送后对话触发状态(唯一标识) ?? false;
	}
	
	public void 设置传送后对话已触发(string 唯一标识, bool 已触发)
	{
		var 存档 = 获取存档();
		存档?.设置传送后对话触发状态(唯一标识, 已触发);
		GD.Print($"对话状态存储: 设置传送后对话触发 {唯一标识} = {已触发}");
	}
	
	// ---------- 条件改变项已执行记录 ----------
	public bool 是否已执行条件改变项(string 条件项路径)
	{
		var 存档 = 获取存档();
		return 存档?.获取条件改变项执行状态(条件项路径) ?? false;
	}
	
	public void 标记条件改变项已执行(string 条件项路径)
	{
		var 存档 = 获取存档();
		if (存档 != null)
		{
			存档.设置条件改变项执行状态(条件项路径, true);
			GD.Print($"对话状态存储: 标记条件改变项已执行 {条件项路径}");
		}
	}
	
	// ---------- 重置所有（新游戏时调用） ----------
	public void 重置所有对话记录()
	{
		var 存档 = 获取存档();
		if (存档 != null)
		{
			存档.已改变对话序列.Clear();
			存档.传送后对话触发记录.Clear();
			存档.已执行条件改变项.Clear();
			存档.对话改变目标序列映射.Clear(); // ★ 新增：同时清空目标序列映射
			GD.Print("对话状态存储: 已重置所有对话记录");
		}
	}
}
