using Godot;
using System;

public partial class 效果_观察弱点 : Node, I卡牌效果
{
	public string 效果名称 => "观察弱点";

	public void 执行效果(卡牌战斗单位 使用者, 卡牌战斗单位 目标, 卡牌实例 卡牌, 卡牌战斗管理器 战斗管理器)
	{
		GD.Print("=== 执行观察弱点效果 ===");

		// 获取强化模式状态
		bool 是否强化 = 战斗管理器.是否强化模式;

		// 根据强化模式决定抽牌次数和伤害加成
		int 抽牌数量 = 是否强化 ? 2 : 1;
		int 伤害加成 = 是否强化 ? 5 : 3;

		// 抽牌提示
		战斗管理器.添加战斗日志($"观察弱点：抽{抽牌数量}张牌，下次攻击伤害+{伤害加成}");

		// 开始抽牌链（可能需要延迟抽第二张）
		开始抽牌(使用者, 战斗管理器, 抽牌数量, 0, 伤害加成);
	}

	/// <summary>
	/// 递归抽牌（按顺序抽，每张之间间隔0.5秒）
	/// </summary>
	private void 开始抽牌(卡牌战斗单位 使用者, 卡牌战斗管理器 战斗管理器, int 总数量, int 当前已抽, int 伤害加成)
	{
		if (当前已抽 >= 总数量)
		{
			// 所有牌抽完，设置伤害加成标记
			观察弱点状态.玩家下次攻击伤害加成 = 伤害加成;
			战斗管理器.添加战斗日志($"发现了敌人的弱点！下次攻击伤害+{伤害加成}");
			战斗管理器.更新UI();
			return;
		}

		// 检查抽牌堆是否为空，若为空则尝试重置
		if (使用者.抽牌堆.Count == 0 && 使用者.弃牌堆.Count > 0)
		{
			使用者.回合开始准备(); // 重置抽牌堆
		}

		// 抽一张牌
		if (使用者.抽牌堆.Count > 0)
		{
			var 抽到的牌 = 使用者.抽牌();
			if (抽到的牌 != null)
			{
				GD.Print($"观察弱点：抽到第{当前已抽 + 1}张牌: {抽到的牌.基础数据?.卡牌名称}");
				战斗管理器.添加战斗日志($"抽到：{抽到的牌.基础数据?.卡牌名称 ?? "未知卡牌"}");

				// 添加到手牌
				var 主场景 = 战斗管理器.GetParent() as 卡牌游戏主场景;
				var 手牌管理器 = 主场景?.玩家手牌管理器;
				手牌管理器?.添加卡牌到手中排队(抽到的牌, true);

				// 抽下一张（延迟0.5秒）
				var 计时器 = new Timer();
				计时器.OneShot = true;
				计时器.WaitTime = 0.5f;
				战斗管理器.AddChild(计时器);
				计时器.Timeout += () =>
				{
					计时器.QueueFree();
					开始抽牌(使用者, 战斗管理器, 总数量, 当前已抽 + 1, 伤害加成);
				};
				计时器.Start();
			}
			else
			{
				// 抽牌失败（理论上不会发生），直接完成
				开始抽牌(使用者, 战斗管理器, 总数量, 当前已抽 + 1, 伤害加成);
			}
		}
		else
		{
			// 无牌可抽，直接完成
			GD.Print("观察弱点：没有牌可抽，直接设置伤害加成");
			观察弱点状态.玩家下次攻击伤害加成 = 伤害加成;
			战斗管理器.添加战斗日志($"发现了敌人的弱点！下次攻击伤害+{伤害加成}");
			战斗管理器.更新UI();
		}
	}

	public string 获取效果描述()
	{
		return "抽1张牌，下次攻击伤害+3；强化时抽2张牌，伤害+5";
	}
}
