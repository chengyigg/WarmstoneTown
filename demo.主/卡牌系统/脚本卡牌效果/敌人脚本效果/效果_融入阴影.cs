using Godot;

public partial class 效果_融入阴影 : RefCounted, I卡牌效果
{
	public string 效果名称 => "融入阴影";
	public void 执行效果(卡牌战斗单位 使用者, 卡牌战斗单位 目标, 卡牌实例 卡牌, 卡牌战斗管理器 战斗管理器)
	{
		战斗管理器.获得护盾(使用者, 4);
		// 抽1张牌
		var 抽到的牌 = 使用者.抽牌();
		if (抽到的牌 != null && 使用者 == 战斗管理器.玩家单位)
		{
			var 主场景 = 战斗管理器.GetParent() as 卡牌游戏主场景;
			主场景?.玩家手牌管理器?.添加卡牌到手中排队(抽到的牌, true);
		}
		战斗管理器.添加战斗日志("融入阴影：获得4点护甲并抽1张牌");
	}
	public string 获取效果描述() => "获得4点护甲，抽1张牌";
}
