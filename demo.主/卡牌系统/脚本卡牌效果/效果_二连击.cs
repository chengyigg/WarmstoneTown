using Godot;
using System;

public partial class 效果_二连击 : Node, I卡牌效果
{
	public string 效果名称 => "二连击";

	public void 执行效果(卡牌战斗单位 使用者, 卡牌战斗单位 目标, 卡牌实例 卡牌, 卡牌战斗管理器 战斗管理器)
	{
		if (战斗管理器.是否强化模式)
		{
			int 单次伤害 = 2;
			for (int i = 1; i <= 5; i++)
			{
				战斗管理器.造成伤害(使用者, 目标, 单次伤害);
				战斗管理器.添加战斗日志($"{卡牌.基础数据.卡牌名称}第{i}次攻击（强化）");
			}
		}
		else
		{
			int 伤害值 = 卡牌.当前伤害;
			战斗管理器.造成伤害(使用者, 目标, 伤害值);
			战斗管理器.添加战斗日志($"{卡牌.基础数据.卡牌名称}第一次攻击");

			int 第二次伤害 = 伤害值;
			战斗管理器.造成伤害(使用者, 目标, 第二次伤害);
			战斗管理器.添加战斗日志($"{卡牌.基础数据.卡牌名称}第二次攻击");
		}
	}

	public string 获取效果描述()
	{
		return "攻击两次，强化模式下变为五次攻击（每次2点伤害）";
	}
}
