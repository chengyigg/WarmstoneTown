// 效果_坚固盾牌.cs
using Godot;
using System;

public partial class 效果_坚固盾牌 : Node, I卡牌效果
{
	public string 效果名称 => "坚固盾牌";
	
	public void 执行效果(卡牌战斗单位 使用者, 卡牌战斗单位 目标, 卡牌实例 卡牌, 卡牌战斗管理器 战斗管理器)
	{
		GD.Print("=== 坚固盾牌效果 ===");
		
		// 添加装备到使用者
		装备管理器.实例?.添加装备(使用者, 卡牌, "坚固盾牌");
		
		// 初始化装备状态
		var 装备 = 装备管理器.实例?.获取装备(使用者, "坚固盾牌");
		if (装备 != null)
		{
			装备.设置效果("已装备", true);
		}
		
		战斗管理器.添加战斗日志("装备了坚固盾牌！每回合开始获得3点护甲，防御牌护甲值+3");
		
		GD.Print("坚固盾牌装备成功");
	}
	
	public string 获取效果描述()
	{
		return "装备后，每回合开始获得3点护甲，防御牌护甲值+3";
	}
}
