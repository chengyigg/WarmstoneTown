// 效果_勇气徽章.cs
using Godot;
using System;

public partial class 效果_勇气徽章 : Node, I卡牌效果
{
	public string 效果名称 => "勇气徽章";
	
	public void 执行效果(卡牌战斗单位 使用者, 卡牌战斗单位 目标, 卡牌实例 卡牌, 卡牌战斗管理器 战斗管理器)
	{
		GD.Print("=== 勇气徽章效果 ===");
		
		// 添加装备到使用者
		装备管理器.实例?.添加装备(使用者, 卡牌, "勇气徽章");
		
		// 初始化计数
		var 装备 = 装备管理器.实例?.获取装备(使用者, "勇气徽章");
		if (装备 != null)
		{
			装备.设置效果("攻击计数", 0);
		}
		
		战斗管理器.添加战斗日志("装备了勇气徽章！每使用3次攻击牌抽1张牌");
		
		GD.Print("勇气徽章装备成功");
	}
	
	public string 获取效果描述()
	{
		return "装备后，每使用3次攻击牌抽1张牌";
	}
}
